#!/usr/bin/env python3
"""Build deterministic Q15 FIR tables and a local ARMv6 converter ELF.

No device/Bluetooth I/O. Uses the existing freestanding toolchain and runtime;
does not require NumPy/SciPy or a target floating-point library.
"""
from datetime import datetime, timezone
import json
import math
import struct

from build_native_sbc import ROOT, LOCAL, run, sha

BUILD=ROOT/'staging/native-pcm-converter'
TAPS=96
CUTOFF=7000
BETA=8.6


def i0(x):
    term=total=1.0
    for k in range(1,100):
        term *= (x*x/4)/(k*k)
        total += term
        if term < total*1e-17: return total
    raise ValueError('Bessel series did not converge')


def kernel(rate,fraction):
    center=(TAPS-1)/2; cutoff=CUTOFF/rate; window=[]
    for j in range(TAPS):
        position=j+fraction-center
        sinc=1.0 if position==0 else math.sin(2*math.pi*cutoff*position)/(2*math.pi*cutoff*position)
        taper=i0(BETA*math.sqrt(max(0,1-((j-center)/center)**2)))/i0(BETA)
        window.append(2*cutoff*sinc*taper)
    total=sum(window)
    integers=[round(x/total*32768) for x in window]
    largest=max(range(TAPS),key=lambda j:abs(integers[j]))
    integers[largest]+=32768-sum(integers)
    if sum(integers)!=32768 or any(not -32768<=x<=32767 for x in integers):
        raise ValueError('Q15 coefficients out of bounds')
    return integers


def main():
    BUILD.mkdir(parents=True,exist_ok=True)
    tables={'32000':[kernel(32000,0)],'44100':[kernel(44100,p/160) for p in range(160)],
            '48000':[kernel(48000,0)]}
    header=BUILD/'pcm_converter_tables.h'
    content=['/* Generated by build_native_pcm_converter.py, not a device patch. */',
             '#include <stdint.h>',f'#define PCM_CONVERTER_TAPS {TAPS}']
    for rate,rows in tables.items():
        if len(rows)==1:
            content.append(f'static const int16_t pcm_{rate}[{TAPS}] = {{'+','.join(map(str,rows[0]))+'};')
        else:
            content.append(f'static const int16_t pcm_{rate}[{len(rows)}][{TAPS}] = {{')
            content.extend('{'+','.join(map(str,row))+'},' for row in rows)
            content.append('};')
    header.write_text('\n'.join(content)+'\n')
    table_path=BUILD/'coefficients.json'
    table_path.write_text(json.dumps({'taps':TAPS,'cutoff_hz':CUTOFF,'kaiser_beta':BETA,
                                      'q_fraction_bits':15,'tables':tables},indent=2)+'\n')
    linker=BUILD/'converter.ld'
    linker.write_text('''ENTRY(pcm_converter_clear)
PHDRS { code PT_LOAD FLAGS(5); data PT_LOAD FLAGS(6); }
SECTIONS {
 . = 0x08000000;
 .text : { *(.text*) } :code
 .rodata : { *(.rodata*) } :code
 . = ALIGN(4096);
 .data : { *(.data*) } :data
 .bss (NOLOAD) : { *(.bss*) *(COMMON) } :data
 /DISCARD/ : { *(.comment) *(.note*) *(.ARM.exidx*) *(.ARM.extab*) }
}
''')
    baseline=json.loads((ROOT/'staging/native-sbc/manifest.json').read_text())
    compiler=baseline['commands'][0][0]; flags=baseline['commands'][0][1:-4]
    sources=[LOCAL/'pcm_converter.c',LOCAL/'runtime.c']; objects=[]; commands=[]
    for source in sources:
        obj=BUILD/(source.stem+'.o')
        cmd=[compiler,*flags,'-I'+str(BUILD),'-c',str(source),'-o',str(obj)]
        run(cmd); objects.append(str(obj)); commands.append(cmd)
    elf=BUILD/'converter-armv6.elf'; flat=BUILD/'converter-armv6.bin'
    cmd=[compiler,'-mcpu=arm1176jzf-s','-marm','-mfloat-abi=soft','-nostdlib','-static','-no-pie',
         '-Wl,--gc-sections,--build-id=none,-Map='+str(BUILD/'converter.map'),
         '-Wl,-T,'+str(linker),'-Wl,--undefined=pcm_converter_reset',
         '-Wl,--undefined=pcm_converter_process',*objects,'-lgcc','-o',str(elf)]
    run(cmd); commands.append(cmd)
    undefined=run(['arm-linux-gnueabi-nm','-u',str(elf)]).strip()
    if undefined: raise ValueError('Unresolved converter symbols: '+undefined)
    symbols={}
    for line in run(['arm-linux-gnueabi-nm','-n',str(elf)]).splitlines():
        parts=line.split()
        if len(parts)==3: symbols[parts[2]]={'address':int(parts[0],16),'type':parts[1]}
    attrs=run(['arm-linux-gnueabi-readelf','-A',str(elf)])
    segments=run(['arm-linux-gnueabi-readelf','-l',str(elf)])
    if 'Tag_CPU_arch: v6' not in attrs or 'INTERP' in segments or 'DYNAMIC' in segments:
        raise ValueError('Unexpected target ISA/runtime')
    run(['arm-linux-gnueabi-objcopy','-O','binary',str(elf),str(flat)])
    manifest={'updated_utc':datetime.now(timezone.utc).isoformat(),
        'elf':str(elf.relative_to(ROOT)),'elf_sha256':sha(elf),
        'flat_binary':str(flat.relative_to(ROOT)),'flat_binary_sha256':sha(flat),
        'flat_binary_bytes':flat.stat().st_size,'symbols':symbols,'commands':commands,
        'source_sha256':{str(p.relative_to(ROOT)):sha(p) for p in
                         [*sources,LOCAL/'pcm_converter.h',header,table_path,linker,
                          ROOT/'scripts/build_native_pcm_converter.py']},
        'coefficient_table':str(table_path.relative_to(ROOT)),
        'coefficient_table_sha256':sha(table_path),'generated_header':str(header.relative_to(ROOT)),
        'taps':TAPS,'cutoff_hz':CUTOFF,'kaiser_beta':BETA,'phases_44100':160,
        'output_format':{'sample_rate':16000,'channels':1,'bits':16},
        'downmix':'stereo arithmetic mean, integer truncation toward zero',
        'rounding':'FIR Q15 round nearest, half away from zero; saturating S16',
        'sources':['https://docs.scipy.org/doc/scipy/reference/generated/scipy.signal.resample_poly.html',
                   'https://docs.scipy.org/doc/scipy/reference/generated/scipy.signal.windows.kaiser.html'],
        'attributes':attrs,'segments':segments,'undefined_symbols':[],
        'linux_runtime_required':False,'device_io':False,'device_install_candidate':False,
        'real_time_performance_verified':False,
        'limitations':'Standalone freestanding converter only. No SBC/AVDTP/native loader/PCM integration supplied by this build. Causal FIR has initial zero history and no automatic tail flush; serialized single-stream ownership is required. Target hardware sample clock/speaker and actual runtime are unverified.'}
    path=BUILD/'manifest.json'; path.write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'manifest':str(path),'flat_binary_bytes':manifest['flat_binary_bytes'],
                      'taps':TAPS,'phases_44100':160,'device_io':False}))


if __name__=='__main__': main()
