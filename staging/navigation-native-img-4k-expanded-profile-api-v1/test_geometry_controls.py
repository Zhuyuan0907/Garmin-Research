#!/usr/bin/env python3
"""Fresh small metadata/arithmetic controls; no full IMG or native CPU run."""
from dataclasses import replace
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import sys
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
spec = importlib.util.spec_from_file_location('expanded4k', HERE / 'expanded_4k_profile.py')
api = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = api
spec.loader.exec_module(api)
CASES = []


def h(raw):
    return hashlib.sha256(raw).hexdigest()


def require(ok, message):
    if not ok:
        raise AssertionError(message)


def fixture():
    raw = bytearray((at * 29 + 7) % 256 for at in range(512))
    raw[0] = 0; raw[15] = 219
    raw[16:23] = b'DSKIMG\0'; raw[65:72] = b'GARMIN\0'
    raw[64] = 8; raw[97:99] = b'\x09\x03'; raw[510:512] = b'\x55\xaa'
    for at, value in ((0x18, 16), (0x1a, 16), (0x1c, 1024), (0x5d, 16), (0x5f, 16), (0x63, 32768)):
        struct.pack_into('<H', raw, at, value)
    struct.pack_into('<I', raw, 0x1ca, 262144)
    return bytes(raw)


def template(name):
    raw = bytearray((at * 13 + 19) % 256 for at in range(512))
    raw[0] = 1; raw[16] = 0
    filename, extension = name.split('.')
    raw[1:12] = filename.encode().ljust(8, b' ') + extension.encode().ljust(3, b' ')
    return bytes(raw)


def reject(name, call, why):
    try:
        call()
    except api.Rejection as error:
        require(why in str(error), name + ': ' + str(error))
        CASES.append({'name': name, 'passed': True, 'expected_rejection': str(error)})
        return
    raise AssertionError('Missing rejection:' + name)


def save(name, value):
    raw = (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode()
    with (HERE / name).open('xb') as f:
        require(f.write(raw) == len(raw), 'Complete evidence write')
    return h(raw)


def main():
    require(not (HERE / 'proof.json').exists(), 'Fresh namespace only')
    prior = ROOT / 'staging/navigation-v3-4k-capacity-readonly-review-v1/proof.json'
    prior_raw = prior.read_bytes()
    require(h(prior_raw) == 'b50914f3ebba65db14d9f6d5ee9ee06fb6e673c9f674c32e7bd107a6304c2ffe', 'Closed narrow review exact hash')
    prior_proof = json.loads(prior_raw)
    require(prior_proof['all_assigned_checks_passed'], 'Closed narrow review passed')
    size_items = tuple((name, prior_proof['whole_v3_payload_as_4KiB_arithmetic']['six_component_logical_sizes_unchanged'][name]) for name in api.NAMES)
    old_writer = ROOT / 'staging/navigation-native-general-writer-v1/native_ap_writer.py'
    old_writer_hash = h(old_writer.read_bytes())
    require(old_writer_hash == 'cb190d5f3c70f0e81e9d49808dff044e4717b5061f749e7720af56aee39b0cf8', 'Old writer not modified')
    raw = fixture()
    binding = api.bind_original_4k_header(raw, source_kind='synthetic-fixture')
    plan = api.plan_expanded_4k(binding, size_items, declared_blocks=37436)
    require((plan.image_blocks, plan.image_bytes, plan.metadata_bytes, plan.directory_rows, plan.declared_sectors) ==
            (37436, 153337856, 90112, 161, 299488), 'Independent exact arithmetic')
    require(plan.installable is False, 'Never installable')
    CASES.append({'name': 'complete_v3_sizes_fit_uint16_4KiB_expanded_arithmetic_only', 'passed': True,
                  'IMG_or_components_allocated': False})
    patched = api.header_bytes_for_offline_control(plan)
    allowed = {0x63, 0x64, 0x1ca, 0x1cb, 0x1cc, 0x1cd}
    changed = [at for at, (a, b) in enumerate(zip(raw, patched)) if a != b]
    require(set(changed) <= allowed and patched[15] == 219 and patched[97:99] == b'\x09\x03', 'Exact allowed header fields')
    require(struct.unpack_from('<H', patched, 0x63)[0] == 37436 and struct.unpack_from('<I', patched, 0x1ca)[0] == 299488,
            'Exact unsigned count and sector mirror')
    require(all(raw[a:a+n] == patched[a:a+n] for a, n in ((0x18, 6), (0x5d, 4), (0x1bf, 7))), 'CHS preserved without acceptance claim')
    CASES.append({'name': '512byte_header_only_count_and_LBA_sector_mirror_changed', 'passed': True,
                  'changed_byte_offsets': [hex(at) for at in changed], 'header_sha256': h(patched)})
    # High block numbers are decoded independently from the generated bytes.
    # This is Python arithmetic; no native reader/CPU proof is implied.
    component = plan.components[1]
    picks = sorted({0, (32768-component.first_block)//240, component.fat_parts - 1})
    for part in picks:
        t = template(component.name)
        wire = api.fat_row_for_offline_control(plan, component.name, part, t)
        values = struct.unpack_from('<240H', wire, 32)
        start = component.first_block + 240 * part
        end = min(start + 240, component.end_block_exclusive)
        require(values[:end-start] == tuple(range(start, end)) and values[end-start:] == (65535,) * (240-(end-start)), 'Independent FAT decode')
        require(wire[:12] == t[:12] and wire[16] == t[16] and wire[19:32] == t[19:32], 'Opaque row bytes')
        require(struct.unpack_from('<H', wire, 17)[0] == part and struct.unpack_from('<I', wire, 12)[0] == (component.logical_bytes if part == 0 else 0), 'Size/part semantics')
        for b in values[:end-start]:
            require(b < 65535 and ((b << 3) * 512) == b * 4096, 'Unsigned high-block sector arithmetic')
        CASES.append({'name': '512byte_FAT_original_opaque_fields_part_' + str(part), 'passed': True,
                      'first_block': start, 'last_block': end-1, 'wire_sha256': h(wire),
                      'native_CPU_executed': False})
    require(any(component.first_block+240*p <= 32768 < min(component.first_block+240*p+240, component.end_block_exclusive) for p in picks), 'Boundary32768 truly included')
    larger = api.plan_expanded_4k(binding, size_items, declared_blocks=65534)
    require(larger.declared_capacity_bytes == 268427264 and larger.image_bytes == plan.image_bytes,
            'Finite maximum non-sentinel declaration')
    CASES.append({'name': 'maximum_uint16_non_sentinel_capacity_is_explicit', 'passed': True})
    reject('installability_always_prohibited', plan.require_installable, 'installation is prohibited')
    for kind, mutated, message in [
        ('short_header', raw[:-1], 'exactly512'),
        ('mutable_header', bytearray(raw), 'immutable'),
        ('XOR', bytes([1])+raw[1:], 'signature'),
        ('signature', raw[:16]+b'BADIMG\0'+raw[23:], 'signature'),
        ('end_marker', raw[:-2]+b'\0\0', 'signature'),
        ('exponent', raw[:98]+b'\x04'+raw[99:], '4KiB'),
        ('directory_sector', raw[:64]+b'\x02'+raw[65:], 'directory'),
        ('opaque_checksum', raw[:15]+b'\0'+raw[16:], 'opaque byte'),
        ('declared_blocks', raw[:99]+b'\xff\xff'+raw[101:], 'geometry'),
        ('sector_mirror', raw[:458]+b'\xff\xff\xff\xff'+raw[462:], 'geometry'),
        ('CHS_sectors', raw[:24]+b'\x20\0'+raw[26:], 'geometry'),
        ('CHS_heads', raw[:26]+b'\x20\0'+raw[28:], 'geometry'),
        ('CHS_cylinders', raw[:28]+b'\xff\x03'+raw[30:], 'geometry'),
    ]:
        reject('source_' + kind, lambda value=mutated: api.bind_original_4k_header(value, source_kind='synthetic-fixture'), message)
    reject('source_provenance_not_explicit', lambda: api.bind_original_4k_header(raw, source_kind='automatic'), 'provenance')
    reject('synthetic_cannot_claim_sealed_stock', lambda: api.bind_original_4k_header(raw, source_kind='sealed-stock-header'), 'hash mismatch')
    reject('forged_header_binding', lambda: api.plan_expanded_4k(replace(binding, sha256='0'*64), size_items, declared_blocks=37436), 'identity changed')
    for value in (None, True, 0, 32768, 65535, 65536, -1):
        reject('declared_blocks_' + repr(value), lambda value=value: api.plan_expanded_4k(binding, size_items, declared_blocks=value), 'integer range')
    reject('declaration_under_required_allocations', lambda: api.plan_expanded_4k(binding, size_items, declared_blocks=37435), 'cannot cover')
    small = tuple((name, 4096) for name in api.NAMES)
    reject('small_image_cannot_bypass_old_profile', lambda: api.plan_expanded_4k(binding, small, declared_blocks=37436), 'original profile')
    for name, altered, why in [
        ('missing_component', size_items[:-1], 'Exactly six'),
        ('reordered_component', size_items[::-1], 'names/order'),
        ('duplicate_component', (size_items[0],)*6, 'names/order'),
        ('unknown_component', (('EVIL.FILE', 240),)+size_items[1:], 'names/order'),
        ('bool_size', ((size_items[0][0], True),)+size_items[1:], 'integer range'),
        ('zero_size', ((size_items[0][0], 0),)+size_items[1:], 'integer range'),
        ('negative_size', ((size_items[0][0], -1),)+size_items[1:], 'integer range'),
        ('size_over_u32', ((size_items[0][0], 0x100000000),)+size_items[1:], 'integer range'),
        ('too_large_for_FAT', (size_items[0], (size_items[1][0], 268435456))+size_items[2:], 'cannot cover'),
    ]:
        reject(name, lambda altered=altered: api.plan_expanded_4k(binding, altered, declared_blocks=37436), why)
    reject('forged_plan_image_count', lambda: api.header_bytes_for_offline_control(replace(plan, image_blocks=plan.image_blocks+1)), 'integrity changed')
    reject('forged_plan_sector_mirror', lambda: api.header_bytes_for_offline_control(replace(plan, declared_sectors=plan.declared_sectors+1)), 'integrity changed')
    reject('unknown_FAT_component', lambda: api.fat_row_for_offline_control(plan, 'MISSING.MDR', 0, template('00004171.MDR')), 'Unknown component')
    reject('negative_FAT_part', lambda: api.fat_row_for_offline_control(plan, component.name, -1, template(component.name)), 'integer range')
    reject('FAT_part_beyond_last', lambda: api.fat_row_for_offline_control(plan, component.name, component.fat_parts, template(component.name)), 'integer range')
    reject('wrong_FAT_template_name', lambda: api.fat_row_for_offline_control(plan, component.name, 0, template('00004171.SRT')), 'identity')
    wrong = bytearray(template(component.name)); wrong[16] = 3
    reject('root_template_as_component', lambda: api.fat_row_for_offline_control(plan, component.name, 0, bytes(wrong)), 'identity')
    require(h(old_writer.read_bytes()) == old_writer_hash, 'Old writer unchanged after controls')
    require(h(prior.read_bytes()) == h(prior_raw), 'Closed review unchanged')
    require(all(c['passed'] for c in CASES), 'All fresh cases pass')
    plan_sha = save('synthetic-v3-size-plan.json', plan.report())
    result = {'schema': 'fresh-small-explicit-4KiB-expanded-geometry-controls/v1',
        'all_cases_passed': True, 'all_assigned_checks_passed': True, 'cases': CASES,
        'case_count': len(CASES), 'source_sha256': h(Path(__file__).read_bytes()),
        'api_sha256': h((HERE/'expanded_4k_profile.py').read_bytes()),
        'plan_sha256': plan_sha, 'closed_review_sha256': h(prior_raw),
        'old_writer_sha256_before_after': old_writer_hash,
        'only_512byte_header_and_FAT_rows_generated_in_memory': True,
        'component_payloads_or_full_IMG_allocated_or_written': False,
        'actual_candidate_or_backup_IMG_opened': False, 'native_CPU_executed': False,
        'old_closed_suite_replayed': False, 'installer_or_device_IO': False,
        'header_checksum_or_AP_renderer_or_full_container_acceptance_verified': False,
        'installable': False, 'rendering_bug_fixed': False,
        'current_physical_baseline_parent_observation': 'Stock AP+Searchv2 with CN off displays roads; v3 regression established, cause not isolated.',
    }
    proof_sha = save('proof.json', result)
    print(json.dumps({'all_cases_passed': True, 'cases': len(CASES), 'proof_sha256': proof_sha,
                      'full_IMG_written': False, 'device_IO': False, 'installable': False}))


if __name__ == '__main__':
    main()
